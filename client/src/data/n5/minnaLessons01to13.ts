import type { VocabularyItem } from '../../types/vocabulary';

export type CompactVocabTuple = [
  kanji: string | null,
  hiragana: string,
  hanViet: string | null,
  meaning: string,
  wordType: string,
  exampleSentence?: string | null,
  exampleMeaning?: string | null,
];

export function buildUnitVocab(
  unitId: number,
  startId: number,
  rows: CompactVocabTuple[],
): VocabularyItem[] {
  return rows.map((row, idx) => ({
    id: startId + idx,
    unitId,
    level: 'N5',
    wordNumber: idx + 1,
    kanji: row[0],
    hiragana: row[1],
    hanViet: row[2],
    meaning: row[3],
    wordType: row[4],
    exampleSentence: row[5] ?? null,
    exampleMeaning: row[6] ?? null,
    notes: null,
  }));
}

