const BASIC_PRACTICE_TYPES: PracticeType[] = [
  'multiple_choice',
  'fill_blank',
  'ja_to_vi',
  'vi_to_ja',
  'grammar_selection',
  'mixed',
];

type RawGrammarRule = [
  code: string,
  name: string,
  hiragana: string,
  meaning: string,
  explanation: string,
  usage: string,
  notes: string,
  pattern: string,
  target: string,
  templatePattern: string,
  templateVi: string,
];

interface RawChapterSpec {
  number: number;
  title: string;
  topics: string[];
  rules: RawGrammarRule[];
}

function buildRule(chapterId: string, raw: RawGrammarRule): SmartGrammarRule {
  const [
    code,
    name,
    hiragana,
    meaning,
    explanation,
    usage,
    notes,
    pattern,
    target,
    templatePattern,
    templateVi,
  ] = raw;
  const id = `N5-MNN-${chapterId}-${code}`;
  return {
    id,
    bookId: 'MINNA_N5',
    chapterId,
    level: 'N5',
    name,
    hiragana,
    meaning,
    explanation,
    usage,
    notes,
    category: 'relation',
    semanticFunction: code.toLowerCase(),
    allowedRelationTypes: [code.toLowerCase()],
    practiceTypes: BASIC_PRACTICE_TYPES,
    patterns: [{ pattern, target }],
    templates: [
      {
        id: `${id}_T1`,
        grammarId: id,
        pattern: templatePattern,
        vietnamesePattern: templateVi,
        slots: [
          { name: 'A', allowedTypes: ['noun'], allowedForms: ['N'] },
          { name: 'B', allowedTypes: ['noun'], allowedForms: ['N'] },
        ],
      },
    ],
  };
}

